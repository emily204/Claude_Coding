import {convertCatalog} from "../fakeshop/catalog-core.mjs";
// Turns a Merch Curator export (merch-catalog.json) into fakeshop/products.js.
// Usage: node scripts/import-catalog.mjs merch-catalog.json [--per-store 40] [--images] [--rate KRW=0.00072 --rate CNY=0.14]
import { readFileSync, writeFileSync } from "node:fs";

const args = process.argv.slice(2);
let input, perStore = 40, withImages = false;
const rates = { USD: 1 };
for (let i = 0; i < args.length; i++) {
  const arg = args[i];
  if (arg === "--images") withImages = true;
  else if (arg === "--per-store") {
    perStore = Number(args[++i]);
    if (!Number.isSafeInteger(perStore) || perStore < 1) throw Error("--per-store needs a positive integer");
  } else if (arg === "--rate") {
    const match = /^([A-Z]{3})=([0-9.eE+-]+)$/i.exec(args[++i] || "");
    if (!match || !Number.isFinite(Number(match[2])) || Number(match[2]) <= 0) throw Error("--rate needs CUR=positive_number");
    rates[match[1].toUpperCase()] = Number(match[2]);
  } else if (!arg.startsWith("--") && !input) input = arg;
  else throw Error("Unknown or extra argument: " + arg);
}
if (!input) { console.error("Usage: node scripts/import-catalog.mjs <merch-catalog.json> [--per-store N] [--images] [--rate CUR=usd_value]"); process.exit(1); }

const data = JSON.parse(readFileSync(input, "utf8"));
if (!Array.isArray(data.products)) { console.error("Not a Merch Curator export: no products array."); process.exit(1); }

const {products: out, skipped} = convertCatalog(data, {perStore, withImages, rates});
if (!out.length) { console.error("No usable products found; nothing written.", skipped); process.exit(1); }
out.sort((a, b) => a.store.localeCompare(b.store) || a.name.localeCompare(b.name));
writeFileSync(new URL("../fakeshop/products.js", import.meta.url),
  "// Generated by scripts/import-catalog.mjs from a Merch Curator export. Edit the export, not this file.\nconst PRODUCTS = " + JSON.stringify(out, null, 1) + ";\n");
// Retain the source snapshot so the live shop can refresh without rebuilding products.js.
writeFileSync(new URL("../fakeshop/data/catalog.json", import.meta.url), JSON.stringify({
  schema_version: 1, exported_at: data.exported_at || new Date().toISOString(), products: data.products,
}, null, 2) + "\n");
const per = {}; out.forEach(o => (per[o.store] = (per[o.store] || 0) + 1));
console.log(`Wrote ${out.length} products`, per, "skipped:", skipped);
